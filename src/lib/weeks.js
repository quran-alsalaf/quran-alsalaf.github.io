// تمييز مقررات الأسابيع بالتناوب (بطلب صاحب المشروع): كل مقرر أسبوع في المذكرات يظهر في
// المصحف بلون خلفية خفيف، والذي يليه عادي، ثم ملوّن، وهكذا — فتتبيّن حدود المقررات بالنظر.
//
// المقررات في memos.json (weeks) مقاطع متصلة من الآيات بترتيب المصحف، والملوّن منها ما كان
// ترتيبه زوجيًّا (الأول ملوّن). والتناوب بترتيب المصحف لا بترتيب المذكرة: فجزء عمّ المرتّب
// في مذكرته من آخره يتناوب كذلك، والأسبوع ذو المقطعين (التين والقدر، وبينهما العلق) يتناوب
// مقطعاه مع ما بينهما.
const cache = new WeakMap();

export function weekMap(quran) {
  let map = cache.get(quran);
  if (map) return map;

  const seg = new Int32Array(quran.verses.length).fill(-1);
  (quran.memos?.weeks ?? []).forEach(([from, to], i) => {
    for (let v = from; v <= to; v++) seg[v] = i;
  });
  // يُلوَّن من الصفحة كلمات الآيات وحدها — لا عنوان السورة ولا البسملة (بقرار صاحب المشروع).
  // وإظهار اللون أو إخفاؤه بإعداد المستخدم (src/lib/settings.js)، لا هنا.
  const tinted = (v) => v >= 0 && seg[v] >= 0 && seg[v] % 2 === 0;

  map = { tinted };
  cache.set(quran, map);
  return map;
}
